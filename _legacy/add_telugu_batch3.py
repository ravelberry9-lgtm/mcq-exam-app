def read_seed_file(filepath):
    """Read the seed file and extract all MCQs"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    return content

def extract_mcqs(content, start_id=31501, end_id=31525):
    """Extract MCQs in specified range"""
    # Pattern to match MCQ tuples - flexible for long explanations
    pattern = r'\(\s*(\d+),\s*([\'"])(.*?)\2,\s*([\'"])(.*?)\4,\s*([\'"])(.*?)\6,\s*([\'"])(.*?)\8,\s*([\'"])(.*?)\10,\s*([\'"])(.*?)\12,\s*([\'"])(.*?)\14,\s*([\'"])(.*?)\16\s*\)'

    mcqs = {}
    for match in re.finditer(pattern, content, re.DOTALL):
        mcq_id = int(match.group(1))
        if start_id <= mcq_id <= end_id:
            question = match.group(3)
            opt_a = match.group(5)
            opt_b = match.group(7)
            opt_c = match.group(9)
            opt_d = match.group(11)
            answer = match.group(13)
            explanation = match.group(15)
            folder = match.group(17)
            topic = match.group(19)

            mcqs[mcq_id] = {
                'question': question,
                'opt_a': opt_a,
                'opt_b': opt_b,
                'opt_c': opt_c,
                'opt_d': opt_d,
                'answer': answer,
                'explanation': explanation,
                'folder': folder,
                'topic': topic,
                'full_match': match.group(0)
            }

    return mcqs

